export function getTranslation(lang = 'hi', key = '') {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS['hi'];
  if (dictionary[key] !== undefined) {
    return dictionary[key];
  }
  // Fallback to Hindi or English
  return TRANSLATIONS['hi'][key] || TRANSLATIONS['en'][key] || key;
}

export function getCropDisplayName(crop, lang = 'hi') {
  if (!crop) return '';
  switch (lang) {
    case 'hi':
      return crop.hindiName || crop.name;
    case 'mr':
      return crop.marathiName || crop.hindiName || crop.name;
    case 'pa':
      return crop.punjabiName || crop.hindiName || crop.name;
    case 'gu':
      return crop.gujaratiName || crop.hindiName || crop.name;
    case 'ta':
      return crop.tamilName || crop.name;
    case 'te':
      return crop.teluguName || crop.name;
    case 'en':
    default:
      return crop.name;
  }
}
